/**
 * Generates the bank logo components in src/components/icon/banks/ from the
 * vendored indian-banks symbols (scripts/vendor/indian-banks, see its README).
 *
 *   node scripts/generate-bank-logos.mjs && npx prettier --write src/components/icon/banks
 *
 * Each logo becomes a forwardRef component importing only React, as
 * CLAUDE.md's icon rule requires: sized in em, role="img" with the bank's
 * name, SVG ids prefixed per bank so two logos on one page never collide.
 *
 * They are NOT added to the app-wide ICONS registry: together they weigh
 * ~300 KB, which every page would download. banks/index.tsx instead loads
 * each one on demand, so a page pays only for the logos it shows.
 */
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { transform } from "@svgr/core";

const VENDOR = "scripts/vendor/indian-banks";
const OUT = "src/components/icon/banks";
const names = JSON.parse(readFileSync(`${VENDOR}/banks.json`, "utf8"));
mkdirSync(OUT, { recursive: true });

const pascal = (slug) => slug.charAt(0).toUpperCase() + slug.slice(1);

const template = (variables, { tpl }) => tpl`
import { forwardRef, type SVGProps } from "react";

export const ${variables.componentName} = forwardRef<SVGSVGElement, SVGProps<SVGSVGElement>>(
  (props, ref) => ${variables.jsx}
);
${variables.componentName}.displayName = "${variables.componentName}";
`;

const entries = [];
for (const file of readdirSync(`${VENDOR}/symbols`).sort()) {
  const slug = file.replace(/\.svg$/, "");
  const name = names[slug];
  if (!name) throw new Error(`No name for ${slug} in banks.json`);
  const componentName = `${pascal(slug)}BankLogo`;
  const svg = readFileSync(`${VENDOR}/symbols/${file}`, "utf8");
  let code = await transform(
    svg,
    {
      plugins: ["@svgr/plugin-svgo", "@svgr/plugin-jsx"],
      typescript: true,
      ref: true,
      dimensions: false,
      svgProps: { width: "1em", height: "1em", role: "img", "aria-label": name },
      expandProps: "end",
      template,
      svgoConfig: {
        plugins: [
          { name: "preset-default", params: { overrides: { removeViewBox: false } } },
          "removeDimensions",
          { name: "prefixIds", params: { prefix: `bank-${slug}`, delim: "-" } },
        ],
      },
    },
    { componentName }
  );
  code = code.replace(
    `export const ${componentName}`,
    `/** ${name}: its symbol from the indian-banks repository. GENERATED by\n * scripts/generate-bank-logos.mjs; edit that, not this file. */\nexport const ${componentName}`
  );
  // A few source files carry legacy SVG/CSS values React's types reject, and
  // stray numeric aria-labels on inner text elements: normalise them.
  code = code
    .replace(/imageRendering: "optimize(Speed|Quality)"/g, 'imageRendering: "auto"')
    .replace(/writingMode: "lr-tb"/g, 'writingMode: "horizontal-tb"')
    .replace(/\s+aria-label=\{[0-9.]+\}/g, "")
    // Editor metadata (Inkscape) that isn't CSS.
    .replace(/\s+Inkscape\w+: "[^"]*",?/g, "");
  writeFileSync(`${OUT}/${componentName}.tsx`, code);
  entries.push({ slug, name, componentName });
}

const index = `"use client";

import { lazy, type SVGProps } from "react";

/**
 * The bank logos in this folder, by IFSC prefix (the first four letters of
 * a branch's IFSC code), with each bank's name. GENERATED by
 * scripts/generate-bank-logos.mjs; edit that, not this file.
 *
 * Each logo is its own lazy component, so a page downloads only the banks it
 * shows (see BankLogo in @/components/common/BankLogo). Render one with
 * <LazyBankLogo slug="hdfc" /> inside a Suspense boundary.
 */
export interface BankLogoEntry {
  slug: string;
  name: string;
}

export const BANK_LOGOS: BankLogoEntry[] = [
${entries.map((e) => `  { slug: "${e.slug}", name: ${JSON.stringify(e.name)} },`).join("\n")}
];

${entries
  .map(
    (e) =>
      `const ${e.componentName}Lazy = lazy(() =>\n  import("@/components/icon/banks/${e.componentName}").then((m) => ({ default: m.${e.componentName} }))\n);`
  )
  .join("\n")}

export function LazyBankLogo({ slug, ...props }: { slug: string } & SVGProps<SVGSVGElement>) {
  switch (slug) {
${entries.map((e) => `    case "${e.slug}":\n      return <${e.componentName}Lazy {...props} />;`).join("\n")}
    default:
      return null;
  }
}
`;
writeFileSync(`${OUT}/index.tsx`, index);
process.stdout.write(`wrote ${entries.length} bank logos and ${OUT}/index.tsx\n`);
