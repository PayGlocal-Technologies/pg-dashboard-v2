export function invoiceLabelsFor(language: string): InvoiceLabels {
  return invoiceLabelsByLanguage[language] ?? EN;
}

/**
 * Languages offered in the picker, derived from the translations themselves.
 *
 * Deriving rather than listing is the point: a hand-written list drifted from
 * this file, so seven of the fifteen offered were rendering in English while the
 * picker cheerfully accepted them — and `language` is persisted into templates
 * and draft memory, so a merchant could store "Korean" and later receive an
 * English document labelled Korean once the renderer honours locale. Now the
 * only way to appear in the picker is to have labels here.
 *
 * English first because it is the default; the rest alphabetically.
 */
export const INVOICE_LANGUAGES: string[] = [
  "English",
  ...Object.keys(invoiceLabelsByLanguage)
    .filter((name) => name !== "English")
    .sort(),
];

export const DEFAULT_INVOICE_LANGUAGE = "English";
