/**
 * The body POSTed to /mca-invoice/{mid}/create.
 *
 * Deliberately its own type rather than `Partial<InvoiceData>`, because the
 * request and the response genuinely differ and pretending otherwise needs a
 * cast that hides real mismatches:
 *
 *  - line items go up as strings (production posts its editing rows verbatim)
 *    and come back as numbers;
 *  - `subTotal`, `userCreateConsent` and `userLinkConsent` are request-only —
 *    the server consumes them and they never appear on InvoiceData;
 *  - `discount`/`tax` carry a computed *Amount on the way up only.
 */
export interface LineItemPayload {
  key: string;
  type: string;
  description: string;
  hsn: string;
  gstRate: string;
  unitPrice: string;
  quantity: string;
  totalPrice: string;
  saveAsSku: boolean;
}

export type InvoiceCreatePayload = Omit<Partial<InvoiceData>, "lineItems" | "discount" | "tax"> & {
  lineItems?: LineItemPayload[];
  subTotal?: number;
  discount?: {
    discountName?: string;
    value?: string;
    type?: string;
    discountAmount?: string;
  };
  tax?: {
    taxName?: string;
    value?: string;
    taxAmount?: string;
  };
  userCreateConsent?: boolean;
  userLinkConsent?: boolean;
};
