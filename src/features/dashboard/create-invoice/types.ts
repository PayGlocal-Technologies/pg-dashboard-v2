// ─── Editor state ─────────────────────────────────────────────────────────────
// The flat form the Nova-derived editor binds to. This is deliberately NOT the
// wire shape: it holds strings where the form needs strings, and it is mapped
// to a full InvoiceData document by toInvoicePayload() in helpers.ts on every
// autosave. Keeping the two apart is what lets the UI stay flat while the API
// stays the step-shaped upsert production already exposes.

/**
 * A line item as edited. Amounts stay strings because they come straight out of
 * text inputs and must survive a half-typed "12." without being coerced to 12.
 */
export interface LineItemDraft {
  /** Local key only; the server does not round-trip it. */
  key: string;
  /** Maps to LineItem.description — the primary label shown on the invoice. */
  description: string;
  /** Maps to LineItem.type. Production requires it, so the dialog does too. */
  type: string;
  hsn: string;
  /** Percent as a bare number string, e.g. "18". Maps to LineItem.gstRate. */
  gstRate: string;
  unitPrice: string;
  quantity: string;
  /** Ticked in the line-item dialog: pushes the item into SKU management. */
  saveAsSku?: boolean;
}

export interface InvoiceFormState {
  /** Server-owned once the draft exists; empty until the first save returns. */
  invoiceNumber: string;
  /** Whether the merchant overrode the auto-generated number. */
  /** YYYY-MM-DD. */
  invoiceDate: string;
  /** YYYY-MM-DD, or "" when unset. */
  dueDate: string;
  /** Which due-term chip is selected. Local only: the API stores dueDate. */
  dueTermId: string | null;

  clientId: string;
  currency: string;
  lineItems: LineItemDraft[];

  discountName: string;
  discountValue: string;
  discountType: "percentage" | "fixed";
  taxName: string;
  taxValue: string;

  accountNo: string;

  memo: string;
  notes: string;
  lut: string;

  logoEnabled: boolean;
  signatureEnabled: boolean;

  isRecurring: boolean;
  recurringType: RecurringType | "";
  recurringStartDate: string;

  userCreateConsent: boolean;
}

