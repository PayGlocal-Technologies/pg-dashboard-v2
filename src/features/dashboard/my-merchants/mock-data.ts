const ORDER: StageKey[] = ["signup", "business", "account", "verification", "activation"];

/** Stages up to `current` done (with their completion dates), `current` in
 *  the given state, the rest pending. */
function stages(
  done: string[],
  current?: { status: Exclude<StageStatus, "done" | "pending">; note: string }
): MerchantStage[] {
  return ORDER.map((key, i): MerchantStage => {
    if (i < done.length) return { key, status: "done", completedAt: done[i] };
    if (i === done.length && current) return { key, status: current.status, note: current.note };
    return { key, status: "pending" };
  });
}

